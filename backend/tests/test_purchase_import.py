    t("선급금", m["prepaid"] == 260514.3)
    t("실지급액", m["actual_paid"] == 639669.6)
    t("실비투자 빈칸은 None", m["invest"] is None)
    t("합계 열은 월이 아니다", len(out["months"]) == 3)

