def main():
    out = PI.parse_workbook(book(SHEET), year=2026)

    t("월 3개", sorted(out["months"]) == ["2026-04", "2026-05", "2026-08"])
    t("못 읽은 줄 없음", out["warnings"] == [])

    m = out["months"]["2026-08"]
    t("매출액", m["revenue"] == 1006562.6)
    t("항목 4개", len(m["items"]) == 4)
    t("항목 순서", [i["key"] for i in m["items"]] ==
      ["raw", "supply", "etc", "outsourcing"])

    raw = m["items"][0]
    t("원소재 매입", raw["buy"] == 1180240.6)
    t("원소재 지급", raw["paid"] == 520110.2)
    t("원소재 잔액", raw["balance"] == 515850)

    # 합계 줄을 외주로 읽으면 여기서 깨진다
    osc = m["items"][3]
